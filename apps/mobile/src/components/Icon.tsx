export type IconName = keyof typeof ICONS;
export type { IconWeight };

/** Status glyphs that read as solid badges even though they have no `-outline` twin here. */
const SOLID: ReadonlySet<IconName> = new Set<IconName>([
  'add-circle',
  'alert-circle',
  'arrow-down-circle',
  'arrow-up-circle',
  'checkmark-circle',
  'checkmark-done-circle',
  'star',
  'warning',
]);

/** A name with an `-outline` twin is the solid one of the pair (an active tab, a ticked box). */
function defaultWeight(name: IconName): IconWeight {
  if (SOLID.has(name)) return 'fill';
  return !name.endsWith(OUTLINE_SUFFIX) && `${name}${OUTLINE_SUFFIX}` in ICONS ? 'fill' : 'regular';
}

export function Icon({
  name,
  size = DEFAULT_SIZE,
  color,
  weight,
}: {
  name: IconName;
  size?: number;
  color?: string;
  /** Overrides the weight implied by the name, e.g. `duotone` inside tinted tiles. */
  weight?: IconWeight;
}) {
  const Glyph = ICONS[name];
  return <Glyph size={size} color={color} weight={weight ?? defaultWeight(name)} />;
}
